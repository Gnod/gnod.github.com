// 教学顺序：踩到就开 → 按钮不在路上 → 一次两条链路 → 倒计时 → 二选一开关
//
// 这一章还负责把三样东西养大（`node tools/coverage.mjs` 量出来的三个最大缺口）：
//   · 静止敌 —— 它在世界一只露过一次面。它不动、不追，价值全在"改变路线的形状"：
//     堵掉捷径、守住光点、把一条支路变成必须精确停住的深井。
//   · 反相门 —— 孤立的反相门只是"按了会关的门"，它只有和常规门并置时才成立。
//     所以它的发育方向不是"更多反相门"，而是"二选一"这个结构的各种变奏。
//   · 计时钮 —— 倒计时的压力全部来自路线有多长，所以它的变奏都在改路线：
//     绕开静止敌、先铺路再冲、一次开两道相隔很远的门。

