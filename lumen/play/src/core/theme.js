// 终点为什么不是绿的，又为什么不是暖白的。
//
// 原来是 #8dff70 —— 全局唯一一个饱和亮绿，看起来不像调过色，像忘了调；
// 而且它和 circuit（#3fe0a4，按钮与闸门）同属绿族。
//
// 第一次换成暖白 #ffeccc，理由是"每个色带都被占了（琥珀=光点、红=敌人、
// 紫=传送门、蓝=加速、灰蓝=单向、绿=机关、纯白=玩家），终点要独一无二
// 就只能靠明度与饱和度而不是色相"。测试当场否决：与光点色相只差 6°。
// 那条断言是为一个真 bug 写的（敌人橙 + 终点金曾经糊成一片暖色，
// 红绿色觉障碍下"会杀你的"和"要走到的"是同一个颜色），不该为审美让路。
//
// 所以终点走冷端：#7ff2ff。它比玩家的光晕 #6fe3ff 更淡更亮，两者不会认错；
// 色相离琥珀和红都很远，两套配色因此在同一个方向上（C_CB 早就是冷青）。
// 意思也还在 —— 你一路带着的那点光，到头来变大了。

// 色觉辅助替代。
// 原则：危险 / 收集 / 终点这三类绝不能落在同一个色系里 ——
// 之前把敌人改成橙、终点改成金，结果和金色的光点挤成一团暖色，
// 红绿色觉障碍下"会杀你的""可以捡的""要走到的"是同一个颜色。
export const C_CB = {
  ...C,
  enemy:    '#ff5aa8',   // 洋红：红绿色觉障碍下仍能与金色光点分开
  enemyDim: '#5a1636',
  goal:     '#9fe8ff',   // 终点改冷色，避开光点的金
  orb:      '#ffeaa8',   // 光点提亮：链路色只剩蓝↔琥珀可用，琥珀会和原来的金撞
  circuit:  '#4fd0ff',
  slide:    '#cfe0f5',   // 色觉辅助下靠明度拉开，不靠色相
};

export let palette = C;
export function setColorblind(on) { palette = on ? C_CB : C; }
export function pal() { return palette; }

// 每个世界给轨道一个不同的冷暖倾向。没有章节标题，只有光的颜色在慢慢变。
