// 每条链路给一个不同色相，配合按钮↔闸门的连线，让"谁配谁"一眼可读。
const LINK_HUE = { a: 158, b: 196, c: 268, d: 34, e: 322, f: 88 };

// 色觉辅助下换成蓝↔琥珀这一组。原来 a=158(绿) 与 b=196(青) 只差 38°，
// 红绿色觉障碍下几乎就是同一个颜色 —— 而多链路房间全靠颜色区分谁配谁。
// 再给各链路错开明度，灰度下也还能分。
const LINK_HUE_CB = { a: 205, b: 42, c: 272, d: 188, e: 22, f: 248 };
const LINK_LIT_CB = { a: 0, b: -6, c: -12, d: 8, e: -16, f: 6 };

export function linkColor(link, light = 58) {
  const k = link[0];                    // 链路名形如 'a@21'，只看基字母
  if (palette === C_CB) {
    return `hsl(${LINK_HUE_CB[k] ?? 205} 78% ${light + (LINK_LIT_CB[k] ?? 0)}%)`;
  }
  return `hsl(${LINK_HUE[k] ?? 158} 70% ${light}%)`;
}
